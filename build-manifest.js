// Usage: node build-manifest.js
// 1. Scans content/ for unit files u<number>.js (K1 u01..u35, K2 u101.., K3 u201..), sorted by
//    number (u35 before u101), and writes content/index.js:
//      window.ACCA_UNIT_FILES = ['content/u01.js', ...];
// 2. Rewrites the BUILD block in sw.js: the offline file list (app files + content units)
//    and the cache name, which is a hash of those files, so any change refreshes the cache.
// Run it again whenever a unit file is added, removed or edited.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = __dirname;
const CONTENT = path.join(ROOT, 'content');
const APP_FILES = ['index.html', 'styles.css', 'app.js', 'manifest.webmanifest', 'icon.svg', 'icon-512.png', 'apple-touch-icon.png'];

function writeIfChanged(file, text) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old === text) return false;
  const tmp = file + '.tmp-' + process.pid;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
  return true;
}

if (!fs.existsSync(CONTENT)) fs.mkdirSync(CONTENT);
const units = fs.readdirSync(CONTENT)
  .filter(f => /^u\d+\.js$/.test(f))
  .sort((a, b) => parseInt(a.slice(1), 10) - parseInt(b.slice(1), 10) || a.localeCompare(b));
const unitPaths = units.map(f => 'content/' + f);

const indexText = '// Generated by build-manifest.js. Do not edit by hand; run `node build-manifest.js`.\n' +
  'window.ACCA_UNIT_FILES = ' + JSON.stringify(unitPaths, null, 2) + ';\n';
const indexChanged = writeIfChanged(path.join(CONTENT, 'index.js'), indexText);

const cached = APP_FILES.concat(['content/index.js'], unitPaths);
const hash = crypto.createHash('sha256');
for (const f of cached) {
  const p = path.join(ROOT, f);
  if (!fs.existsSync(p)) { console.error('missing file: ' + f); process.exit(1); }
  hash.update(f + '\0');
  hash.update(fs.readFileSync(p));
  hash.update('\0');
}
const cacheName = 'acca-study-' + hash.digest('hex').slice(0, 12);

const swFile = path.join(ROOT, 'sw.js');
const sw = fs.readFileSync(swFile, 'utf8');
const re = /(\/\/ BUILD:START\r?\n)[\s\S]*?(\/\/ BUILD:END)/;
if (!re.test(sw)) { console.error('sw.js: BUILD:START / BUILD:END markers not found'); process.exit(1); }
const block = 'var CACHE = ' + JSON.stringify(cacheName) + ';\n' +
  'var FILES = ' + JSON.stringify(['./'].concat(cached.map(f => './' + f)), null, 2) + ';\n';
const swChanged = writeIfChanged(swFile, sw.replace(re, (_, a, b) => a + block + b));

console.log(units.length + ' unit file(s): ' + (units.join(', ') || '(none)'));
console.log('content/index.js ' + (indexChanged ? 'written' : 'unchanged'));
console.log('sw.js cache ' + cacheName + ' (' + (cached.length + 1) + ' entries) ' + (swChanged ? 'written' : 'unchanged'));
